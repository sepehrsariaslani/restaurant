def make_cooked_rice():
    company_res = frappe.db.sql('SELECT company FROM tabBOM WHERE is_active = 1 AND company IS NOT NULL LIMIT 1')
    default_company = company_res[0][0] if company_res else None
    currency_res = frappe.db.sql('SELECT currency, conversion_rate FROM tabBOM WHERE is_active = 1 AND currency IS NOT NULL LIMIT 1')
    default_currency = currency_res[0][0] if currency_res else 'ریال'
    default_conversion = currency_res[0][1] if currency_res else 1.0
    print('Company: ' + str(default_company) + ' Currency: ' + str(default_currency))
    boms = frappe.get_list('BOM', filters={'is_active': 1}, fields=['name', 'item', 'company', 'currency', 'conversion_rate'])
    print('Total active BOMs: ' + str(len(boms)))
    cooked_name = 'برنج پخته شده'
    replaced = 0
    for bom_info in boms:
        bom_doc = frappe.get_doc('BOM', bom_info.name)
        has_raw_rice = False
        raw_qty = 0
        for itm in list(bom_doc.items):
            if itm.item_code == 'برنج سفید':
                has_raw_rice = True
                raw_qty = itm.qty
                bom_doc.items.remove(itm)
                break
        if has_raw_rice:
            bom_doc.append('items', {'item_code': cooked_name, 'qty': raw_qty, 'uom': 'گرم', 'rate': 0})
            if not bom_doc.company and default_company:
                bom_doc.company = default_company
            if not bom_doc.currency and default_currency:
                bom_doc.currency = default_currency
                bom_doc.conversion_rate = default_conversion
            bom_doc.save()
            frappe.db.commit()
            replaced += 1
            print('  ' + bom_doc.item + ': ' + str(raw_qty) + 'g raw -> ' + str(raw_qty) + 'g cooked')
    print('Replaced in ' + str(replaced) + ' BOMs')
